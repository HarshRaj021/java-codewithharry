public class incrementDecrement {
    public static void main(String[] args) {

        int a = 5;
        int b = 5;
        int c = 5;
        int d = 5;

        // Pre-increment
        System.out.println(++a); // 6

        // Post-increment
        System.out.println(b++); // 5
        System.out.println(b);   // 6

        // Pre-decrement
        System.out.println(--c); // 4

        // Post-decrement
        System.out.println(d--); // 5
        System.out.println(d);   // 4
    }
}
    

